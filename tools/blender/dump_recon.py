"""Dump a ground-truth report of one .blend to markdown.
Run: blender -b --disable-autoexec FILE.blend --python dump_recon.py -- OUT.md
Counts are EVALUATED (modifiers applied), which is what an FBX export would contain.
"""
import bpy, sys, os, re
from mathutils import Vector

out = sys.argv[sys.argv.index("--") + 1]
dg = bpy.context.evaluated_depsgraph_get()
sc = bpy.context.scene
L = []
w = L.append

def base(n):
    return re.sub(r"(\.\d{3})+$", "", n)

rows = []
for o in bpy.data.objects:
    if o.type not in ('MESH', 'CURVE', 'FONT', 'SURFACE', 'META'):
        continue
    eo = o.evaluated_get(dg)
    try:
        me = eo.to_mesh()
        me.calc_loop_triangles()
        tris = len(me.loop_triangles); verts = len(me.vertices)
        eo.to_mesh_clear()
    except Exception:
        tris = verts = -1
    ws = [o.matrix_world @ Vector(c) for c in eo.bound_box]
    mn = Vector(map(min, *ws)); mx = Vector(map(max, *ws))
    rows.append(dict(
        name=o.name, base=base(o.name), type=o.type, parent=o.parent.name if o.parent else "",
        dim=mx - mn, ctr=(mn + mx) / 2, mn=mn, mx=mx, scale=o.scale, tris=tris, verts=verts,
        mats=[m.name for m in o.data.materials if m] if hasattr(o.data, "materials") else [],
        mods=[m.type + (":%d" % m.levels if m.type == 'SUBSURF' else "") for m in o.modifiers],
        hidden=o.hide_render or o.hide_viewport,
        uv=len(o.data.uv_layers) if o.type == 'MESH' else 0,
    ))

w("# Recon: %s\n" % os.path.basename(bpy.data.filepath))
w("Generated by tools/blender/dump_recon.py (Blender %s). Source file written by Blender %s.\n" % (bpy.app.version_string, ".".join(map(str, bpy.data.version))))
w("- Units: %s, scale_length=%s" % (sc.unit_settings.system, sc.unit_settings.scale_length))
w("- Mesh-like objects: %d | evaluated triangles: %d | evaluated verts: %d" % (len(rows), sum(r['tris'] for r in rows), sum(r['verts'] for r in rows)))
if rows:
    mn = Vector(map(min, *[r['mn'] for r in rows])); mx = Vector(map(max, *[r['mx'] for r in rows]))
    d = mx - mn
    w("- Overall bounds (m): X %.2f  Y %.2f  Z %.2f  | min (%.2f, %.2f, %.2f) max (%.2f, %.2f, %.2f)" % (d.x, d.y, d.z, *mn, *mx))
w("- Lights: %s" % [(l.name, l.type, round(l.energy, 1)) for l in bpy.data.lights])
w("- Cameras: %d | Collections: %s | Actions(animation): %d" % (len(bpy.data.cameras), [c.name for c in bpy.data.collections], len(bpy.data.actions)))

w("\n## Images / textures\n")
w("| image | source | packed | file exists | size |")
w("|---|---|---|---|---|")
for i in bpy.data.images:
    if i.name in ("Render Result", "Viewer Node"):
        continue
    ex = os.path.exists(bpy.path.abspath(i.filepath)) if i.filepath else False
    w("| %s | %s | %s | %s | %s |" % (i.name, i.filepath or "-", bool(i.packed_file), ex, tuple(i.size)))

w("\n## Materials\n")
w("| material | uses_nodes | image textures | shader nodes |")
w("|---|---|---|---|")
for m in bpy.data.materials:
    imgs, types = [], set()
    if m.use_nodes and m.node_tree:
        for n in m.node_tree.nodes:
            if n.type == 'TEX_IMAGE' and n.image:
                imgs.append(n.image.name)
            elif n.type not in ('OUTPUT_MATERIAL', 'TEX_COORD', 'MAPPING', 'NORMAL_MAP', 'REROUTE', 'GROUP'):
                types.add(n.type)
    w("| %s | %s | %s | %s |" % (m.name, m.use_nodes, ", ".join(imgs) or "-", ", ".join(sorted(types))[:80]))

w("\n## Object groups (name with .NNN suffix stripped), sorted by total triangles\n")
w("| group | count | tris each (max) | total tris | typical dim (m) | modifiers | materials |")
w("|---|---|---|---|---|---|---|")
groups = {}
for r in rows:
    groups.setdefault(r['base'], []).append(r)
for k, v in sorted(groups.items(), key=lambda kv: -sum(x['tris'] for x in kv[1])):
    r0 = max(v, key=lambda x: x['tris'])
    w("| %s | %d | %d | %d | %.2f x %.2f x %.2f | %s | %s |" % (
        k, len(v), r0['tris'], sum(x['tris'] for x in v), r0['dim'].x, r0['dim'].y, r0['dim'].z,
        ",".join(sorted(set(sum([x['mods'] for x in v], [])))) or "-", ", ".join(r0['mats'][:3]) or "-"))

w("\n## Every object (largest bounding extent first)\n")
w("| name | type | dim x,y,z (m) | centre x,y,z | obj scale | tris | modifiers | materials | hidden |")
w("|---|---|---|---|---|---|---|---|---|")
for r in sorted(rows, key=lambda r: -r['dim'].length):
    w("| %s | %s | %.2f, %.2f, %.2f | %.1f, %.1f, %.1f | %.2f,%.2f,%.2f | %d | %s | %s | %s |" % (
        r['name'], r['type'], *r['dim'], *r['ctr'], *r['scale'], r['tris'],
        ",".join(r['mods']) or "-", ", ".join(r['mats'][:2]) or "-", r['hidden']))

with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(L) + "\n")
print("WROTE", out)
